import pandas as pd

# ========================================
# サンプルデータの作成
# ========================================

df = pd.DataFrame({
    "year": [2024, 2024, 2024],
    "month": [1, 2, 3],
    "day": [15, 20, 10],
    "birth_year": [1990, 1985, 1995],
    "text": [
        "購入しました",
        "検討中です",
        "返品希望"
    ]
})

print("===== 加工前 =====")
print(df)


# ========================================
# 1. 年・月・日から日付を作成
# ========================================

df["date"] = pd.to_datetime(
    df[["year", "month", "day"]]
)


# ========================================
# 2. 日付から曜日を作成
# ========================================

df["day_of_week"] = df["date"].dt.day_name()


# ========================================
# 3. 生まれた年から年齢を作成
# ========================================

df["age"] = 2024 - df["birth_year"]


# ========================================
# 4. 購入フラグを作成
# ========================================

df["is_purchase"] = (
    df["text"]
    .str.contains("購入")
    .astype(int)
)


# ========================================
# 5. 返品フラグを作成
# ========================================

df["is_return"] = (
    df["text"]
    .str.contains("返品")
    .astype(int)
)


print("\n===== 加工後 =====")
print(df)