import pandas as pd
import unicodedata

# ========================================
# サンプルデータの作成
# ========================================

df = pd.DataFrame({
    "city": [
        " 東京 ",
        "とうきょう",
        "Tokyo",
        "TOKYO",
        "東京都"
    ],
    "code": [
        "Ａ１２３",
        "B456",
        "Ｃ７８９",
        "D012",
        "Ｅ３４５"
    ],
    "name": [
        "田中 太郎",
        "鈴木　花子",
        "佐藤 一郎",
        "山田　美咲",
        "高橋 健"
    ]
})

print("===== 修正前 =====")
print(df)


# ========================================
# 1. 前後の空白を削除
# ========================================

df["city"] = df["city"].str.strip()


# ========================================
# 2. 英字を小文字に統一
# ========================================

df["city"] = df["city"].str.lower()


# ========================================
# 3. 半角・全角スペースを削除
# ========================================

df["name"] = df["name"].str.replace(" ", "", regex=False)
df["name"] = df["name"].str.replace("　", "", regex=False)


# ========================================
# 4. 都市名を統一
# ========================================

mapping = {
    "とうきょう": "東京",
    "tokyo": "東京",
    "東京都": "東京"
}

df["city"] = df["city"].replace(mapping)


# ========================================
# 5. 全角文字 → 半角文字
# ========================================

df["code"] = df["code"].apply(
    lambda x: unicodedata.normalize("NFKC", x)
)


print("\n===== 修正後 =====")
print(df)