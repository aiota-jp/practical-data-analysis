import pandas as pd

# サンプルデータの作成
df = pd.DataFrame({
    "name": ["田中", "鈴木", "田中", "佐藤", "鈴木"],
    "age": [25, 30, 25, 28, 30],
    "city": ["東京", "大阪", "東京", "名古屋", "大阪"]
})

# 元のデータを表示
print("===== 元のデータ =====")
print(df)


# ========================================
# 1. 完全一致する重複行を削除
#    最初の行を残す
# ========================================

df_unique = df.drop_duplicates()

print("\n===== 重複行を削除（最初の行を残す） =====")
print(df_unique)


# ========================================
# 2. 完全一致する重複行を削除
#    最後の行を残す
# ========================================

df_unique = df.drop_duplicates(keep="last")

print("\n===== 重複行を削除（最後の行を残す） =====")
print(df_unique)


# ========================================
# 3. name列を基準に重複行を削除
# ========================================

df_unique = df.drop_duplicates(subset=["name"])

print("\n===== name列を基準に重複削除 =====")
print(df_unique)


# ========================================
# 4. 重複しているデータを全て削除
# ========================================

df_unique = df.drop_duplicates(keep=False)

print("\n===== 重複データを全て削除 =====")
print(df_unique)