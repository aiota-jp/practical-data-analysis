import pandas as pd

# サンプルデータの作成
df = pd.DataFrame({
    "id": [1, 2, 3, 4, 5],
    "category": ["食品", "家電", "食品", "衣類", "家電"],
    "date": pd.to_datetime([
        "2024-01-01",
        "2024-02-15",
        "2024-03-20",
        "2024-04-10",
        "2024-05-05"
    ])
})

print("===== 変換前 =====")
print(df)

print("\n===== 変換前のデータ型 =====")
print(df.dtypes)


# ========================================
# カテゴリ型に変換
# ========================================

df["category"] = df["category"].astype("category")


# ========================================
# 日付から年・月・曜日を取得
# ========================================

df["year"] = df["date"].dt.year
df["month"] = df["date"].dt.month

# 0=月曜日 ～ 6=日曜日
df["day_of_week"] = df["date"].dt.dayofweek


# ========================================
# 数値 → 文字列
# ========================================

df["id_str"] = df["id"].astype(str)


print("\n===== 変換後 =====")
print(df)

print("\n===== 変換後のデータ型 =====")
print(df.dtypes)