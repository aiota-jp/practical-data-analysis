import pandas as pd

# サンプルデータの作成
df = pd.DataFrame({
    "id": ["1", "2", "3", "4", "5"],
    "price": ["1000", "2000", "3000", "N/A", "5000"],
    "date": [
        "2024-01-01",
        "2024-01-02",
        "2024-01-03",
        "2024-01-04",
        "2024-01-05"
    ],
    "is_active": [1, 0, 1, 1, 0]
})

# ========================================
# 変換前
# ========================================

print("===== 変換前のデータ =====")
print(df)

print("\n===== 変換前のデータ型 =====")
print(df.dtypes)


# ========================================
# 文字列 → 整数型
# ========================================

df["id"] = df["id"].astype(int)


# ========================================
# 文字列 → 数値型
# ========================================

# 変換できない値はNaNにする
df["price"] = pd.to_numeric(
    df["price"],
    errors="coerce"
)


# ========================================
# 文字列 → 日付型
# ========================================

df["date"] = pd.to_datetime(df["date"])


# ========================================
# 整数 → 真偽値型
# ========================================

df["is_active"] = df["is_active"].astype(bool)


# ========================================
# 変換後
# ========================================

print("\n===== 変換後のデータ =====")
print(df)

print("\n===== 変換後のデータ型 =====")
print(df.dtypes)