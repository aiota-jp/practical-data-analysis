import pandas as pd

# ========================================
# サンプルデータの作成
# ========================================

df = pd.DataFrame({
    "id": [1, 2, 3, 4, 5],
    "name": [
        "田中",
        "鈴木",
        "佐藤",
        "山田",
        "高橋"
    ],
    "age": [25, 30, 0, 35, -1],
    "status": [
        "active",
        "active",
        "active",
        "deleted",
        "active"
    ],
    "created_at": [
        "2024-01-01",
        "2024-01-02",
        "2024-01-03",
        "2024-01-04",
        "2024-01-05"
    ],
    "updated_at": [
        "2024-02-01",
        "2024-02-02",
        "2024-02-03",
        "2024-02-04",
        "2024-02-05"
    ]
})

print("===== 削除前 =====")
print(df)


# ========================================
# 1. 不要な列を削除
# ========================================

df = df.drop(
    columns=["id", "created_at", "updated_at"]
)

print("\n===== 不要な列を削除 =====")
print(df)


# ========================================
# 2. statusがdeletedの行を除外
# ========================================

df = df[df["status"] != "deleted"]

print("\n===== 削除済みデータを除外 =====")
print(df)


# ========================================
# 3. 年齢が0以下の行を除外
# ========================================

df = df[df["age"] > 0]

print("\n===== 年齢が0以下のデータを除外 =====")
print(df)


# ========================================
# 最終結果
# ========================================

print("\n===== 最終データ =====")
print(df)