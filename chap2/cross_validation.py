import pandas as pd
from sklearn.model_selection import cross_val_score
from sklearn.linear_model import LinearRegression

# ========================================
# サンプルデータの作成
# ========================================

df = pd.DataFrame({
    "age": [
        25, 30, 35, 40, 45,
        28, 32, 38, 42, 50,
        27, 31, 36, 41, 46,
        29, 33, 39, 44, 52
    ],
    "experience": [
        2, 5, 8, 12, 18,
        4, 6, 10, 15, 22,
        3, 5, 9, 13, 19,
        4, 7, 11, 16, 24
    ],
    "salary": [
        300, 400, 450, 500, 600,
        350, 420, 480, 550, 700,
        320, 410, 460, 520, 620,
        370, 430, 490, 580, 720
    ]
})

print("===== 元のデータ =====")
print(df)


# ========================================
# 特徴量（X）と目的変数（y）に分離
# ========================================

X = df[["age", "experience"]]
y = df["salary"]

print("\n===== 特徴量（X） =====")
print(X)

print("\n===== 目的変数（y） =====")
print(y)


# ========================================
# 線形回帰モデルの作成
# ========================================

model = LinearRegression()


# ========================================
# 5分割交差検証
# ========================================

scores = cross_val_score(
    model,
    X,
    y,
    cv=5,
    scoring="r2"
)


# ========================================
# 評価結果
# ========================================

print("\n===== 5分割交差検証の結果 =====")

for i, score in enumerate(scores, start=1):
    print(f"{i}回目: {score:.4f}")

print("\n===== 全体評価 =====")
print(f"平均スコア: {scores.mean():.4f}")
print(f"標準偏差    : {scores.std():.4f}")